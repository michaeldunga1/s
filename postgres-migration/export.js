function literal(value) {
  if (value === null) return 'NULL';
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  if (typeof value !== 'string' || value.includes('\0')) {
    throw new Error('Unsupported SQLite value: expected text without NUL or a safe integer.');
  }
  return `'${value.replace(/'/g, "''")}'`;
}

function exportSql(app, filename, dryRun) {
  const spec = specs[app];
  if (!spec) throw new Error(`Unknown application: ${app}`);
  const appDir = path.resolve(__dirname, '..', app);
  const Database = createRequire(path.join(appDir, 'package.json'))('better-sqlite3');
  const db = new Database(filename || path.join(appDir, spec.file), { readonly: true, fileMustExist: true });
  try {
    db.exec('BEGIN');
    if (db.pragma('integrity_check', { simple: true }) !== 'ok') throw new Error('SQLite integrity check failed.');
    if (db.pragma('foreign_key_check').length) throw new Error('SQLite foreign key check failed.');
    const sourceTables = db.prepare("SELECT name FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%'").all().map(row => row.name);
    const unknown = sourceTables.filter(name => !spec.tables.some(([table]) => table === name));
    if (unknown.length) throw new Error(`Unknown source tables: ${unknown.join(', ')}`);
    for (const [table, columns] of spec.tables) {
      if (!sourceTables.includes(table)) throw new Error(`Missing source table: ${table}`);
      const actual = db.prepare(`PRAGMA table_info("${table}")`).all().map(column => column.name);
      if (actual.length !== columns.length || actual.some(column => !columns.includes(column))) {
        throw new Error(`Unexpected columns in source table: ${table}`);
      }
    }

    const sql = [
      'BEGIN;', 'SET LOCAL standard_conforming_strings = on;', 'SET LOCAL search_path = public, pg_catalog;',
      `DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f')) THEN
          RAISE EXCEPTION 'Destination public schema is not empty';
        END IF;
      END $$;`, spec.schema
    ];
    const sequenceExists = db.prepare("SELECT 1 FROM sqlite_schema WHERE type = 'table' AND name = 'sqlite_sequence'").get();
    for (const [table, columns] of spec.tables) {
      const rows = db.prepare(`SELECT ${columns.map(column => `"${column}"`).join(', ')} FROM "${table}"`).iterate();
      let count = 0;
      for (const row of rows) {
        sql.push(`INSERT INTO "${table}" (${columns.map(column => `"${column}"`).join(', ')}) VALUES (${columns.map(column => literal(row[column])).join(', ')});`);
        count++;
      }
      sql.push(`DO $$ BEGIN IF (SELECT count(*) FROM "${table}") <> ${count} THEN RAISE EXCEPTION 'Row count mismatch for ${table}'; END IF; END $$;`);
      const sequence = sequenceExists ? db.prepare('SELECT seq FROM sqlite_sequence WHERE name = ?').get(table)?.seq : null;
      if (sequence !== null && sequence !== undefined && (!Number.isSafeInteger(sequence) || sequence < 0)) throw new Error(`Invalid sequence for ${table}`);
      const floor = sequence || 0;
      sql.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST(COALESCE((SELECT MAX(id) FROM "${table}"), 0), ${floor}, 1), GREATEST(COALESCE((SELECT MAX(id) FROM "${table}"), 0), ${floor}) > 0);`);
    }
    sql.push(spec.afterData, dryRun ? 'ROLLBACK;' : 'COMMIT;');
    db.exec('COMMIT');
    return sql.join('\n') + '\n';
  } finally {
    db.close();
  }
}

if (require.main === module) {
  try {
    const [app, option, ...extra] = process.argv.slice(2);
    if (!app || (option && option !== '--dry-run') || extra.length) throw new Error('Usage: node export.js <luo2english|mumamaler> [--dry-run]');
    process.stdout.write(exportSql(app, process.env.DB_PATH, option === '--dry-run'));
  } catch (error) {
    console.error(`Export failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { exportSql, specs };
