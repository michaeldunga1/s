#!/usr/bin/env node

const Database = require('better-sqlite3');
const path = require('node:path');

const tables = [
  ['users', ['id', 'username', 'email', 'password_hash', 'role']],
  ['authors', ['id', 'name']],
  ['categories', ['id', 'name']],
  ['hymns', ['id', 'number', 'title', 'lyrics', 'author_id', 'legacy_url', 'composer', 'page_number', 'slug']],
  ['favorites', ['user_id', 'hymn_id']],
  ['bookmarks', ['user_id', 'hymn_id', 'note', 'tags']],
  ['hymn_categories', ['hymn_id', 'category_id']],
  ['app_migrations', ['name']],
  ['settings', ['key', 'value']]
];

const schema = `
CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  email text,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin'))
);
CREATE UNIQUE INDEX users_username_nocase ON users (lower(username COLLATE "C"));
CREATE UNIQUE INDEX users_email_nocase ON users (lower(email COLLATE "C"));
CREATE TABLE authors (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE UNIQUE INDEX authors_name_nocase ON authors (lower(name COLLATE "C"));
CREATE TABLE categories (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE UNIQUE INDEX categories_name_nocase ON categories (lower(name COLLATE "C"));
CREATE TABLE hymns (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number integer UNIQUE CHECK (number > 0),
  title text NOT NULL,
  lyrics text NOT NULL,
  author_id integer REFERENCES authors(id),
  legacy_url text,
  composer text NOT NULL DEFAULT '',
  page_number integer CHECK (page_number IS NULL OR page_number > 0),
  slug text NOT NULL UNIQUE CHECK (slug <> '' AND slug ~ '[^0-9]')
);
CREATE TABLE favorites (
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  hymn_id integer NOT NULL REFERENCES hymns(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, hymn_id)
);
CREATE TABLE bookmarks (
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  hymn_id integer NOT NULL REFERENCES hymns(id) ON DELETE CASCADE,
  note text NOT NULL DEFAULT '',
  tags text NOT NULL DEFAULT '',
  PRIMARY KEY (user_id, hymn_id)
);
CREATE TABLE hymn_categories (
  hymn_id integer NOT NULL REFERENCES hymns(id) ON DELETE CASCADE,
  category_id integer NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  PRIMARY KEY (hymn_id, category_id)
);
CREATE TABLE app_migrations (name text PRIMARY KEY);
CREATE TABLE settings (key text PRIMARY KEY, value text NOT NULL);
`;

function literal(value) {
  if (value === null) return 'NULL';
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  if (typeof value !== 'string' || value.includes('\0')) {
    throw new Error('Unsupported SQLite value: expected text without NUL or a safe integer.');
  }
  return `'${value.replace(/'/g, "''")}'`;
}

function exportSql(filename, dryRun) {
  const db = new Database(filename, { readonly: true, fileMustExist: true });
  try {
    db.exec('BEGIN');
    if (db.pragma('integrity_check', { simple: true }) !== 'ok') throw new Error('SQLite integrity check failed.');
    if (db.pragma('foreign_key_check').length) throw new Error('SQLite foreign key check failed.');
    const sourceTables = db.prepare("SELECT name FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%'").all().map(row => row.name);
    const unknown = sourceTables.filter(name => !tables.some(([table]) => table === name));
    if (unknown.length) throw new Error(`Unknown source tables: ${unknown.join(', ')}`);
    for (const [table, columns] of tables) {
      if (table === 'settings' && !sourceTables.includes(table)) continue;
      if (!sourceTables.includes(table)) throw new Error(`Missing source table: ${table}`);
      const actual = db.prepare(`PRAGMA table_info("${table}")`).all().map(column => column.name);
      if (actual.length !== columns.length || actual.some(column => !columns.includes(column))) {
        throw new Error(`Unexpected columns in source table: ${table}`);
      }
    }

    const sql = [
      'BEGIN;',
      "SET LOCAL standard_conforming_strings = on;",
      'SET LOCAL search_path = public, pg_catalog;',
      `DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f')) THEN
          RAISE EXCEPTION 'Destination public schema is not empty';
        END IF;
      END $$;`,
      schema
    ];
    for (const [table, columns] of tables) {
      if (!sourceTables.includes(table)) continue;
      const rows = db.prepare(`SELECT ${columns.map(column => `"${column}"`).join(', ')} FROM "${table}"`).iterate();
      let count = 0;
      for (const row of rows) {
        sql.push(`INSERT INTO "${table}" (${columns.map(column => `"${column}"`).join(', ')}) VALUES (${columns.map(column => literal(row[column])).join(', ')});`);
        count++;
      }
      sql.push(`DO $$ BEGIN IF (SELECT count(*) FROM "${table}") <> ${count} THEN RAISE EXCEPTION 'Row count mismatch for ${table}'; END IF; END $$;`);
    }
    for (const table of ['users', 'authors', 'categories', 'hymns']) {
      sql.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM "${table}"), 1), EXISTS (SELECT 1 FROM "${table}"));`);
    }
    sql.push(dryRun ? 'ROLLBACK;' : 'COMMIT;');
    db.exec('COMMIT');
    return sql.join('\n') + '\n';
  } finally {
    db.close();
  }
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--dry-run') || args.length > 1) throw new Error('Usage: node scripts/export-postgres.js [--dry-run]');
    const filename = process.env.DB_PATH || path.join(__dirname, '..', 'data', 'wendenyasaye.db');
    process.stdout.write(exportSql(filename, args.includes('--dry-run')));
  } catch (error) {
    console.error(`Export failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { exportSql, schema };
